def _css_string(value: str) -> str:
    value = value.strip()
    inner = value
    if (
        len(value) >= 2
        and value[0] == value[-1]
        and value[0] in "\"'"
        and value.count(value[0]) == 2
    ):
        inner = value[1:-1]
    if re.fullmatch(r"[A-Za-z0-9 ]+", inner):
        return f'"{inner}"'
    # A font stack such as '"Inter Variable", Inter, sans-serif' stays as written.
    return value


def _px(value: str, root: str | None) -> str:
    """Turn app ``rem`` into px at the app's root size.

    Material sets ``html { font-size: 125% }``, so an app ``0.25rem`` would
    render 25% larger in the docs. Without a known root size, keep ``rem``.
    """
    match = re.fullmatch(r"(\d+(?:\.\d+)?)rem", str(value).strip())
    base = re.fullmatch(r"(\d+(?:\.\d+)?)px", str(root or "").strip())
    if not match or not base:
        return value
    px = float(match.group(1)) * float(base.group(1))
    return f"{px:g}px"


def _var_key(value: str) -> str:
    """CSS custom-property suffix: ``0.5`` -> ``0-5``, ``2xl`` -> ``2xl``."""
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")


