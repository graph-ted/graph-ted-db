def _optional_groups(tokens: dict) -> str:
    chunks: list[str] = []
    root = (tokens.get("layout") or {}).get("root_font_size")
    radius = tokens.get("radius")
    if isinstance(radius, dict) and radius:
        radius = {key: _px(value, root) for key, value in radius.items()}
        panel = next(
            (radius[key] for key in ("md", "l3", "default", "base", "sm") if key in radius), None
        )
        # Chakra buttons and inputs use the l2 control radius; panels use md.
        control = next((radius[key] for key in ("l2", "sm") if key in radius), panel)
        lines = [":root {"]
        for key, value in radius.items():
            lines.append(f"  --gt-radius-{_var_key(key)}: {value};")
        lines.append("}")
        if control:
            lines.extend(
                [
                    "",
                    ".md-typeset .md-button,",
                    ".md-search__form,",
                    ".md-search__input {",
                    f"  border-radius: {control};",
                    "}",
                ]
            )
        if panel:
            lines.extend(
                [
                    "",
                    ".md-typeset pre,",
                    ".md-typeset pre > code,",
                    ".md-typeset .admonition,",
                    ".md-typeset details {",
                    f"  border-radius: {panel};",
                    "}",
                ]
            )
        chunks.append("\n".join(lines))
    spacing = tokens.get("spacing")
    if isinstance(spacing, dict) and spacing:
        lines = [":root {"]
        for key, value in spacing.items():
            lines.append(f"  --gt-space-{_var_key(key)}: {_px(value, root)};")
        lines.append("}")
        chunks.append("\n".join(lines))
    shadow = tokens.get("shadow")
    if isinstance(shadow, dict) and shadow:
        flat = {key: value for key, value in shadow.items() if isinstance(value, str)}
        lines = []
        if flat:
            lines.append(":root {")
            for key, value in flat.items():
                lines.append(f"  --gt-shadow-{_var_key(key)}: {value};")
            lines.append("}")
        # Chakra semantic shadows carry a light and a dark value.
        for scheme, mode in (("default", "light"), ("slate", "dark")):
            scoped = {
                key: value[mode]
                for key, value in shadow.items()
                if isinstance(value, dict) and mode in value
            }
            if scoped:
                if lines:
                    lines.append("")
                lines.append(f'[data-md-color-scheme="{scheme}"] {{')
                for key, value in scoped.items():
                    lines.append(f"  --gt-shadow-{_var_key(key)}: {value};")
                lines.append("}")
        card_key = next((key for key in ("card", "md", "default") if key in shadow), None)
        card = None
        if card_key:
            card = (
                shadow[card_key]
                if isinstance(shadow[card_key], str)
                else f"var(--gt-shadow-{_var_key(card_key)})"
            )
        if card:
            lines.extend(
                [
                    "",
                    ".md-typeset .admonition,",
                    ".md-typeset details {",
                    f"  box-shadow: {card};",
                    "}",
                ]
            )
        chunks.append("\n".join(lines))
    button = tokens.get("button")
    if isinstance(button, dict) and button:
        lines = [
            "/* App buttons: Chakra button recipe, default size. */",
            ".md-typeset .md-button {",
            "  display: inline-flex;",
            "  align-items: center;",
            "  justify-content: center;",
        ]
        if button.get("height"):
            lines.append(f"  min-height: {_px(button['height'], root)};")
        if button.get("padding_x"):
            lines.append(f"  padding: 0 {_px(button['padding_x'], root)};")
        if button.get("font_size"):
            lines.append(f"  font-size: {_px(button['font_size'], root)};")
        if button.get("line_height"):
            lines.append(f"  line-height: {_px(button['line_height'], root)};")
        lines.append("}")
        chunks.append("\n".join(lines))
    if not chunks:
        return ""
    return "\n\n".join(chunks) + "\n"


